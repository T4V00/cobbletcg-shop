def update(name, idx):
    path = os.path.join(ROOT, name)
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    for k, v in KEYS.items():
        data[k] = v[idx]
    with open(path, "w", encoding="utf-8") as f:
        f.write(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    print(f"{name}: {len(KEYS)} keys")


