#!/usr/bin/env python3
"""1.0 shop tiers: textures, models, blockstates, loot tables and the Paper stall recipe for the NEW shop cores
(paper, brick, copper, lapis, amethyst). Same style as tools/gen_shop_assets.py (striped awning + shop window on the
sides, coin symbol on top) with a material pattern per tier. Only writes these new files; the 7 pre-1.0 cores are
still generated by gen_shop_assets.py.

Original pixel art, generated here (no external assets).
"""
import json
import random
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent / "common/src/main/resources"
A = ROOT / "assets/tcgshop"
_spec = importlib.util.spec_from_file_location("gt", HERE / "gen_textures.py")
gt = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gt)
png, hexc = gt.png, gt.hexc

# tier key -> base color (same as ShopTier.color)
NEW_TIERS = {"paper": "E9DFC4", "brick": "A4553E", "copper": "C8703F", "lapis": "2F5FC8", "amethyst": "A066D8"}


def shade(c, k):
    r, g, b, a = c
    return (max(0, min(255, int(r * k))), max(0, min(255, int(g * k))), max(0, min(255, int(b * k))), a)


def mix(c1, c2, t):
    return tuple(int(c1[i] + (c2[i] - c1[i]) * t) for i in range(3)) + (255,)


# ------------------------------------------------------------------ material patterns (16x16 background)

def noise(base, seed):
    rnd = random.Random(seed)
    c = hexc(base)
    return [[shade(c, 0.85 + rnd.random() * 0.25) for _ in range(16)] for _ in range(16)]


def paper_bg(base, seed):
    """Light paper/cardboard with faint horizontal fibres."""
    rnd = random.Random(seed)
    c = hexc(base)
    px = [[shade(c, 0.94 + rnd.random() * 0.08) for _ in range(16)] for _ in range(16)]
    for y in range(0, 16, 3):
        for x in range(16):
            if rnd.random() < 0.5:
                px[y][x] = shade(c, 0.9)
    return px


def brick_bg(base, seed):
    """Bricks 4 px high, offset every row, with light mortar."""
    rnd = random.Random(seed)
    c = hexc(base)
    mortar = hexc("C9BBA8")
    px = [[shade(c, 0.85 + rnd.random() * 0.25) for _ in range(16)] for _ in range(16)]
    for y in range(16):
        row = y // 4
        for x in range(16):
            if y % 4 == 3 or (x + (4 if row % 2 else 0)) % 8 == 7:
                px[y][x] = shade(mortar, 0.92 + rnd.random() * 0.1)
    return px


def copper_bg(base, seed):
    """Copper plates with rivets and a few oxidized (green) spots."""
    rnd = random.Random(seed)
    c = hexc(base)
    ox = hexc("4FA88A")
    px = [[shade(c, 0.88 + rnd.random() * 0.22) for _ in range(16)] for _ in range(16)]
    for i in range(16):
        px[i][7] = shade(c, 0.7)
        px[7][i] = shade(c, 0.7)
    for (x, y) in [(1, 1), (5, 1), (9, 1), (14, 1), (1, 9), (14, 9), (9, 9), (5, 9)]:
        px[y][x] = shade(c, 1.3)
    for _ in range(14):
        x, y = rnd.randrange(16), rnd.randrange(16)
        px[y][x] = shade(ox, 0.9 + rnd.random() * 0.2)
    return px


def lapis_bg(base, seed):
    """Deep blue with lighter flecks and a few golden specks (like lapis stone)."""
    rnd = random.Random(seed)
    c = hexc(base)
    px = [[shade(c, 0.8 + rnd.random() * 0.25) for _ in range(16)] for _ in range(16)]
    for _ in range(26):
        x, y = rnd.randrange(16), rnd.randrange(16)
        px[y][x] = mix(c, hexc("8FB4FF"), 0.5 + rnd.random() * 0.3)
    for _ in range(6):
        x, y = rnd.randrange(16), rnd.randrange(16)
        px[y][x] = hexc("E8C35A")
    return px


def amethyst_bg(base, seed):
    """Purple crystal facets: diagonal light/dark bands."""
    rnd = random.Random(seed)
    c = hexc(base)
    px = [[shade(c, 0.85 + rnd.random() * 0.15) for _ in range(16)] for _ in range(16)]
    for y in range(16):
        for x in range(16):
            d = (x + 2 * y) % 9
            if d == 0:
                px[y][x] = mix(c, hexc("F2D9FF"), 0.6)
            elif d in (1, 2):
                px[y][x] = shade(c, 1.12)
            elif d == 6:
                px[y][x] = shade(c, 0.7)
    return px


BG = {"paper": paper_bg, "brick": brick_bg, "copper": copper_bg, "lapis": lapis_bg, "amethyst": amethyst_bg}
# awning colors (stripe A, stripe B, scallop A, scallop B): the Paper stall gets a lemonade-yellow awning
AWNING = {"paper": ("F2C94C", "FFF8E0", "B88A1C", "D8CFAF")}
DEFAULT_AWNING = ("D63A3A", "F4F0E8", "8E1F1F", "C9C2B4")


# ------------------------------------------------------------------ faces

def awning(px, key):
    a, b, ea, eb = (hexc(v) for v in AWNING.get(key, DEFAULT_AWNING))
    for y in range(0, 5):
        for x in range(16):
            px[y][x] = a if (x // 2) % 2 == 0 else b
    for x in range(16):
        px[5][x] = ea if x % 2 == 0 else eb


def window(px, c):
    """Shop window with a card (same as the pre-1.0 cores)."""
    for y in range(7, 14):
        for x in range(3, 13):
            px[y][x] = hexc("9FD8F0") if (x + y) % 5 else hexc("CDEFFB")
    for y in range(8, 13):
        for x in range(6, 10):
            px[y][x] = hexc("F2C230") if y in (8, 12) or x in (6, 9) else hexc("3A6FD8")
    for x in range(2, 14):
        px[6][x] = shade(c, 0.6)
        px[14][x] = shade(c, 0.6)
    for y in range(6, 15):
        px[y][2] = shade(c, 0.6)
        px[y][13] = shade(c, 0.6)


def stall_front(px):
    """Paper stall: a wooden counter with a single card on a little stand and a price tag (no glass window)."""
    plank, plank_d = hexc("B5844F"), hexc("8A5E34")
    for y in range(10, 16):
        for x in range(16):
            px[y][x] = plank_d if y in (10, 15) or x % 5 == 0 else shade(plank, 0.95 + ((x * 7 + y * 3) % 5) * 0.03)
    # card on a stand above the counter
    for y in range(6, 10):
        for x in range(6, 10):
            px[y][x] = hexc("F2C230") if y == 6 or x in (6, 9) else hexc("3A6FD8")
    px[9][5] = px[9][10] = plank_d
    # price tag
    for (x, y) in [(12, 7), (13, 7), (12, 8), (13, 8)]:
        px[y][x] = hexc("FFFFFF")
    px[8][11] = hexc("6B6B6B")


def side(key, base):
    c = hexc(base)
    px = BG[key](base, base + key)
    awning(px, key)
    if key == "paper":
        stall_front(px)
    else:
        window(px, c)
    return px


def top(key, base):
    c = hexc(base)
    px = BG[key](base, base + key + "t")
    for i in range(16):
        px[0][i] = px[15][i] = px[i][0] = px[i][15] = shade(c, 0.55)
    coin = hexc("FFFFFF") if key != "paper" else hexc("6B4A2A")
    for (x, y) in [(6, 4), (7, 4), (8, 4), (9, 4), (6, 5), (10, 5), (6, 6), (10, 6), (6, 7), (7, 7), (8, 7), (9, 7),
                   (6, 8), (6, 9), (6, 10), (6, 11), (4, 9), (5, 9), (7, 9), (8, 9)]:
        px[y][x] = coin
    return px


def bottom(key, base):
    """Underside: plain material (the Paper stall has a wooden base)."""
    if key == "paper":
        return noise("8A5E34", "paper_bottom")
    return BG[key](base, base + key + "b")


# ------------------------------------------------------------------ files

def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2), encoding="utf-8")


def main():
    tex = A / "textures/block"
    tex.mkdir(parents=True, exist_ok=True)
    lt = ROOT / "data/tcgshop/loot_table/blocks"
    for key, col in NEW_TIERS.items():
        name = f"shop_core_{key}"
        png(tex / f"{name}_side.png", side(key, col))
        png(tex / f"{name}_top.png", top(key, col))
        png(tex / f"{name}_bottom.png", bottom(key, col))
        write(A / f"models/block/{name}.json", {"parent": "minecraft:block/cube_bottom_top",
              "textures": {"side": f"tcgshop:block/{name}_side", "top": f"tcgshop:block/{name}_top",
                           "bottom": f"tcgshop:block/{name}_bottom"}})
        write(A / f"blockstates/{name}.json", {"variants": {"": {"model": f"tcgshop:block/{name}"}}})
        write(A / f"models/item/{name}.json", {"parent": f"tcgshop:block/{name}"})
        write(lt / f"{name}.json", {"type": "minecraft:block", "pools": [{"rolls": 1,
              "entries": [{"type": "minecraft:item", "name": f"tcgshop:{name}"}],
              "conditions": [{"condition": "minecraft:survives_explosion"}]}]})
    # Paper stall: 1 diamond (the "cash") on a wooden counter under a paper awning
    write(ROOT / "data/tcgshop/recipe/shop_core_paper.json", {
        "type": "minecraft:crafting_shaped",
        "category": "misc",
        "pattern": ["PPP", "SDS", "LLL"],
        "key": {
            "P": {"item": "minecraft:paper"},
            "S": {"item": "minecraft:stick"},
            "D": {"item": "minecraft:diamond"},
            "L": {"tag": "minecraft:wooden_slabs"}
        },
        "result": {"id": "tcgshop:shop_core_paper", "count": 1}
    })
    print("1.0 shop cores generated:", ", ".join(NEW_TIERS))


if __name__ == "__main__":
    main()
