package dev.tcgshop.client.render;

import dev.tcgshop.TcgShop;
import dev.tcgshop.entity.NpcIdentity;
import org.jetbrains.annotations.Nullable;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import net.minecraft.client.Minecraft;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.resources.ResourceManager;

/**
 * NPC skins (1.0): 64x64 player-format textures with both layers painted (hair volume, caps, glasses, hoods,
 * jackets, aprons, skirts, coat tails and sneakers live on the outer layer), generated by tools/gen_npc_skins.py into
 * {@code assets/tcgshop/textures/entity/npc/}:
 * <ul>
 *   <li>{@code <role>_<f|m>_<n>.png}: per role and sex; female skins use the slim model (3px arms);</li>
 *   <li>{@code fixed_<n>.png}: the 10 fixed unique customers ({@link #FIXED_PREFIX} ids, see {@link NpcIdentity#fixedSkin},
 *       or role key {@code tcgshop.role.fixed} with the raw id as skin int);</li>
 *   <li>{@code backpack_<n>.png}: textures of the 3D backpack some NPCs carry (TcgNpcRenderer).</li>
 * </ul>
 * The textures of each role/sex set are found by probing n = 0, 1, 2... so a resource pack can add more skins by
 * continuing the numbering. Roles are the last part of the role key ("tcgshop.role.rival.scalper" -> scalper);
 * anything that is not a special role (customer types, regulars, event visitors) uses the customer set.
 */
public final class NpcSkins {
    private NpcSkins() {}

    /** Prefix of the fixed skin ids ("fixed_0" .. "fixed_9"). */
    public static final String FIXED_PREFIX = NpcIdentity.FIXED_PREFIX;

    /** Roles with their own skin sets (must match tools/gen_npc_skins.py COUNTS). */
    private static final String[] ROLES = {
            "customer", "cashier", "guard", "wholesaler", "beggar", "black_market", "furniture_seller", "trader", "scalper",
            "mayor", "engineer"}; // 1.1 NPC update
    private static final int MAX_PROBE = 512;
    public static final int BACKPACK_COLORS = 8;

    /** Backpack color of each fixed skin (-1 = none); straps are painted in the skin. */
    private static final int[] FIXED_BACKPACK = {-1, 5, -1, 2, -1, -1, -1, -1, -1, -1};

    private static final ResourceLocation FALLBACK = ResourceLocation.fromNamespaceAndPath("minecraft", "textures/entity/player/wide/steve.png");

    /** What to draw: texture, slim (female) model and backpack color (-1 = no backpack). */
    public record Look(ResourceLocation texture, boolean slim, int backpack) {}

    /** Probed sets per role, one map per sex (no string building per frame). */
    private static final Map<String, Look[]> SETS_F = new HashMap<>(), SETS_M = new HashMap<>();
    /** Role key -> skin role (avoids a substring per frame). */
    private static final Map<String, String> ROLE_CACHE = new HashMap<>();
    private static final Look[] FIXED = new Look[NpcIdentity.FIXED_COUNT];
    private static final ResourceLocation[] BACKPACKS = new ResourceLocation[BACKPACK_COLORS];
    private static final Look FALLBACK_LOOK = new Look(FALLBACK, false, -1);

    /** Skin role of a role key (last segment if it is a special role or "fixed", otherwise "customer"). */
    public static String role(@Nullable String roleKey) {
        if (roleKey == null) return "customer";
        String cached = ROLE_CACHE.get(roleKey);
        if (cached != null) return cached;
        String r = roleKey.substring(roleKey.lastIndexOf('.') + 1), out = "customer";
        if (r.equals("fixed")) out = "fixed";
        else for (String k : ROLES) if (k.equals(r)) out = k;
        if (ROLE_CACHE.size() < 256) ROLE_CACHE.put(roleKey, out);
        return out;
    }

    /** Client init: drop the probed skin sets on resource reload (F3+T, resource packs adding or removing skins). */
    public static void initClient() {
        dev.masterball.api.platform.ClientPlatform.INSTANCE.clientReloadListener(
                ResourceLocation.fromNamespaceAndPath(TcgShop.MOD_ID, "npc_skins"), manager -> clearCache());
    }

    /**
     * Look of an NPC. name: its displayed name (decides the sex of skins that don't store one; may be null).
     * Cached: returns shared instances, cheap enough to call every frame.
     */
    public static Look look(@Nullable String roleKey, int skin, @Nullable String name) {
        if (NpcIdentity.isFixedSkin(skin)) return fixed(NpcIdentity.fixedIndex(skin));
        String role = role(roleKey);
        // unique customers (CustomerEntity.applyFixed): role "tcgshop.role.fixed" + the raw id 0..9 as skin
        if (role.equals("fixed")) return fixed(Math.floorMod(skin, NpcIdentity.FIXED_COUNT));
        NpcIdentity.Sex sex = NpcIdentity.sexOf(skin, name);
        Look[] set = set(role, sex);
        if (set.length == 0 && !role.equals("customer")) set = set("customer", sex);
        if (set.length == 0) return FALLBACK_LOOK;
        return set[Math.floorMod(NpcIdentity.skinVariant(skin), set.length)];
    }

    /** Look of a fixed skin by id ("fixed_3"); null if the id is not a fixed skin. */
    @Nullable
    public static Look fixedLook(String skinId) {
        int s = NpcIdentity.fixedSkin(skinId);
        return s < 0 ? null : fixed(NpcIdentity.fixedIndex(s));
    }

    /** Texture of a backpack color (0..7). */
    public static ResourceLocation backpackTexture(int color) {
        int i = Math.floorMod(color, BACKPACK_COLORS);
        ResourceLocation id = BACKPACKS[i];
        if (id == null) BACKPACKS[i] = id = ResourceLocation.fromNamespaceAndPath(TcgShop.MOD_ID, "textures/entity/npc/backpack_" + i + ".png");
        return id;
    }

    /** Same rule as tools/gen_npc_skins.py (where the straps are painted). */
    static int backpack(String role, boolean male, int n) {
        boolean has = switch (role) {
            case "customer" -> n % 5 == 2;
            case "scalper" -> n % 2 == 0;
            default -> false;
        };
        return has ? (n * 3 + (male ? 1 : 0)) % BACKPACK_COLORS : -1;
    }

    /** Clears the probed sets (e.g. after a resource reload that adds skins). */
    public static void clearCache() {
        SETS_F.clear();
        SETS_M.clear();
        java.util.Arrays.fill(FIXED, null);
    }

    private static Look fixed(int i) {
        Look l = FIXED[i];
        if (l == null) {
            ResourceLocation id = ResourceLocation.fromNamespaceAndPath(TcgShop.MOD_ID, "textures/entity/npc/" + FIXED_PREFIX + i + ".png");
            FIXED[i] = l = new Look(id, NpcIdentity.FIXED_SEX[i] == NpcIdentity.Sex.FEMALE, FIXED_BACKPACK[i]);
        }
        return l;
    }

    private static Look[] set(String role, NpcIdentity.Sex sex) {
        boolean female = sex == NpcIdentity.Sex.FEMALE;
        Map<String, Look[]> sets = female ? SETS_F : SETS_M;
        Look[] s = sets.get(role);
        if (s != null) return s;
        String key = role + (female ? "_f" : "_m");
        ResourceManager rm = Minecraft.getInstance().getResourceManager();
        List<Look> list = new ArrayList<>();
        for (int n = 0; n < MAX_PROBE; n++) {
            ResourceLocation id = ResourceLocation.fromNamespaceAndPath(TcgShop.MOD_ID, "textures/entity/npc/" + key + "_" + n + ".png");
            if (rm.getResource(id).isEmpty()) break;
            list.add(new Look(id, female, backpack(role, !female, n)));
        }
        if (list.isEmpty()) TcgShop.LOGGER.warn("No NPC skins found for {} (textures/entity/npc/{}_0.png)", key, key);
        s = list.toArray(new Look[0]);
        sets.put(role, s);
        return s;
    }

    // ---- pre-1.0 API (kept for compatibility)

    /** @deprecated the model depends on the sex now; use {@link #look}. */
    @Deprecated
    public static boolean slim(int index) {
        return look(null, index, null).slim();
    }

    /** @deprecated use {@link #look}. */
    @Deprecated
    public static ResourceLocation texture(String roleKey, int index) {
        return look(roleKey, index, null).texture();
    }
}
