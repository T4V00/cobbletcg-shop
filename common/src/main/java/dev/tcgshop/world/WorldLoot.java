package dev.tcgshop.world;

import dev.masterball.api.platform.Platform;
import dev.tcgshop.TcgShop;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.tags.TagKey;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.entity.BlockEntityType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.levelgen.GenerationStep;
import net.minecraft.world.level.levelgen.feature.Feature;
import net.minecraft.world.level.levelgen.feature.configurations.NoneFeatureConfiguration;
import net.minecraft.world.level.levelgen.placement.PlacedFeature;
import net.minecraft.world.level.levelgen.structure.StructureType;
import net.minecraft.world.level.levelgen.structure.pieces.StructurePieceType;
import net.minecraft.world.level.material.MapColor;

/**
 * 1.0 world loot: searchable trash cans and the "Bankrupt Card Shop" structure.
 * Call {@link #register()} from TcgShop.onInitialize (the static registrations happen when the class loads).
 *
 * <p>Data (generated by tools/gen_worldloot_assets.py): worldgen/configured_feature + placed_feature
 * trash_can_street / trash_can_wild, worldgen/structure + structure_set bankrupt_card_shop, biome tags
 * has_structure/bankrupt_card_shop and spawns_wild_trash_cans, the block's loot table and recipe.
 */
public final class WorldLoot {
    private WorldLoot() {}

    public static final TrashCanBlock TRASH_CAN = Registry.register(BuiltInRegistries.BLOCK, id("trash_can"),
            new TrashCanBlock(BlockBehaviour.Properties.of().mapColor(MapColor.METAL).strength(1.5f, 6f)
                    .sound(SoundType.LANTERN).noOcclusion()));
    public static final Item TRASH_CAN_ITEM = Registry.register(BuiltInRegistries.ITEM, id("trash_can"),
            new BlockItem(TRASH_CAN, new Item.Properties()));
    public static final BlockEntityType<TrashCanBlockEntity> TRASH_CAN_BE = Registry.register(BuiltInRegistries.BLOCK_ENTITY_TYPE, id("trash_can"),
            BlockEntityType.Builder.of(TrashCanBlockEntity::new, TRASH_CAN).build(null));

    public static final Feature<NoneFeatureConfiguration> STREET_CANS = Registry.register(BuiltInRegistries.FEATURE, id("trash_can_street"), new TrashCanFeature(true));
    public static final Feature<NoneFeatureConfiguration> WILD_CANS = Registry.register(BuiltInRegistries.FEATURE, id("trash_can_wild"), new TrashCanFeature(false));

    public static final StructureType<BankruptShopStructure> BANKRUPT_SHOP_TYPE = Registry.register(BuiltInRegistries.STRUCTURE_TYPE,
            id("bankrupt_card_shop"), (StructureType<BankruptShopStructure>) () -> BankruptShopStructure.CODEC);
    public static final StructurePieceType BANKRUPT_SHOP_PIECE = Registry.register(BuiltInRegistries.STRUCTURE_PIECE,
            id("bankrupt_card_shop"), (StructurePieceType.ContextlessType) BankruptShopPiece::new);

    public static final ResourceKey<PlacedFeature> STREET_CANS_PLACED = ResourceKey.create(Registries.PLACED_FEATURE, id("trash_can_street"));
    public static final ResourceKey<PlacedFeature> WILD_CANS_PLACED = ResourceKey.create(Registries.PLACED_FEATURE, id("trash_can_wild"));
    /** Biomes with lonely trash cans (plains, meadows, savannas...). */
    public static final TagKey<Biome> WILD_CAN_BIOMES = TagKey.create(Registries.BIOME, id("spawns_wild_trash_cans"));

    private static ResourceLocation id(String path) {
        return ResourceLocation.fromNamespaceAndPath(TcgShop.MOD_ID, path);
    }

    public static void register() {
        WorldLootConfig.load();
        if (WorldLootConfig.INSTANCE.trashCansWorldgen) {
            // street cans look for dirt paths themselves: any overworld biome can hold a village street
            Platform.INSTANCE.addFeature(Platform.BiomeFilter.overworld(), GenerationStep.Decoration.VEGETAL_DECORATION, STREET_CANS_PLACED);
            Platform.INSTANCE.addFeature(Platform.BiomeFilter.tag(WILD_CAN_BIOMES), GenerationStep.Decoration.VEGETAL_DECORATION, WILD_CANS_PLACED);
        }
    }
}
