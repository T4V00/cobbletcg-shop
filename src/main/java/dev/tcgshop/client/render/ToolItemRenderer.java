package dev.tcgshop.client.render;

import dev.tcgshop.TcgShop;
import dev.tcgshop.item.TcgItems;
import net.fabricmc.fabric.api.client.model.loading.v1.FabricBakedModelManager;
import net.fabricmc.fabric.api.client.model.loading.v1.ModelLoadingPlugin;
import net.fabricmc.fabric.api.client.rendering.v1.BuiltinItemRendererRegistry;
import net.minecraft.client.MinecraftClient;
import net.minecraft.client.render.VertexConsumerProvider;
import net.minecraft.client.render.model.BakedModel;
import net.minecraft.client.render.model.BakedModelManager;
import net.minecraft.client.render.model.json.ModelTransformationMode;
import net.minecraft.client.util.math.MatrixStack;
import net.minecraft.item.Item;
import net.minecraft.item.ItemStack;
import net.minecraft.util.Identifier;

import java.util.ArrayList;
import java.util.List;

/**
 * 1.0 beta 3: 3D tool items. The item model (models/item/&lt;name&gt;.json, generated by tools/gen_items_3d.py) is a
 * builtin/entity model that only carries the display transforms; this renderer then draws
 * <ul>
 *   <li>in the GUI: the classic 2D sprite (models/item/icon/&lt;name&gt;.json), crisp at 16 px;</li>
 *   <li>everywhere else (hands, ground, item frames, head/face slot): the Blockbench-style 3D model
 *       (models/item/3d/&lt;name&gt;.json).</li>
 * </ul>
 * Both inner models are plain baked JSON models (no display of their own), so the cost is one map lookup per draw.
 * The phone has its own renderer ({@link PhoneItemRenderer}) that also picks the tier.
 */
public final class ToolItemRenderer implements BuiltinItemRendererRegistry.DynamicItemRenderer {
    private final Identifier icon, model;

    private ToolItemRenderer(String name) {
        this.icon = iconId(name);
        this.model = modelId(name);
    }

    public static Identifier iconId(String name) {
        return Identifier.of(TcgShop.MOD_ID, "item/icon/" + name);
    }

    public static Identifier modelId(String name) {
        return Identifier.of(TcgShop.MOD_ID, "item/3d/" + name);
    }

    /** Call ONCE from TcgShopClient.onInitializeClient (before the first resource reload). */
    public static void register() {
        List<Identifier> extra = new ArrayList<>();
        tool(TcgItems.NERD_GLOVES, "nerd_gloves", extra);
        tool(TcgItems.MANAGER_GOGGLES, "manager_goggles", extra);
        tool(TcgItems.DEODORANT_SPRAY, "deodorant_spray", extra);
        tool(TcgItems.MOP, "mop", extra);
        tool(TcgItems.REPAIR_KIT, "repair_kit", extra);
        tool(TcgItems.GENERAL_BINDER, "general_binder", extra);
        tool(TcgItems.PERSONAL_BINDER, "personal_binder", extra);
        tool(dev.tcgshop.luxury.LuxuryBlocks.MANSION_KEY, "mansion_key", extra);
        PhoneItemRenderer.register(extra);
        // the inner models have no item/block pointing at them: load and bake them explicitly
        ModelLoadingPlugin.register(ctx -> ctx.addModels(extra));
    }

    private static void tool(Item item, String name, List<Identifier> extra) {
        extra.add(iconId(name));
        extra.add(modelId(name));
        BuiltinItemRendererRegistry.INSTANCE.register(item, new ToolItemRenderer(name));
    }

    @Override
    public void render(ItemStack stack, ModelTransformationMode mode, MatrixStack matrices, VertexConsumerProvider vertexConsumers,
                       int light, int overlay) {
        draw(mode == ModelTransformationMode.GUI ? icon : model, stack, mode, matrices, vertexConsumers, light, overlay);
    }

    /**
     * Draws a baked extra model in place of the builtin one. ItemRenderer has already applied the entry model's display
     * transform and translated by -0.5; renderItem translates by -0.5 again, so undo it first. The inner models have
     * identity transforms (and leftHanded only mirrors a non-identity transform), so nothing is applied twice.
     */
    static void draw(Identifier id, ItemStack stack, ModelTransformationMode mode, MatrixStack matrices, VertexConsumerProvider vcp,
                     int light, int overlay) {
        MinecraftClient mc = MinecraftClient.getInstance();
        BakedModelManager manager = mc.getBakedModelManager();
        BakedModel baked = ((FabricBakedModelManager) manager).getModel(id); // models added through addModels
        if (baked == null) baked = manager.getMissingModel();
        matrices.push();
        matrices.translate(0.5F, 0.5F, 0.5F);
        mc.getItemRenderer().renderItem(stack, mode, false, matrices, vcp, light, overlay, baked);
        matrices.pop();
    }
}
