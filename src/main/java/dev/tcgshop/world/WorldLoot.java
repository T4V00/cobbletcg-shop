package dev.tcgshop.world;

import dev.tcgshop.TcgShop;
import net.fabricmc.fabric.api.biome.v1.BiomeModifications;
import net.fabricmc.fabric.api.biome.v1.BiomeSelectors;
import net.minecraft.block.AbstractBlock;
import net.minecraft.block.MapColor;
import net.minecraft.block.entity.BlockEntityType;
import net.minecraft.item.BlockItem;
import net.minecraft.item.Item;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.registry.RegistryKey;
import net.minecraft.registry.RegistryKeys;
import net.minecraft.registry.tag.TagKey;
import net.minecraft.sound.BlockSoundGroup;
import net.minecraft.structure.StructurePieceType;
import net.minecraft.util.Identifier;
import net.minecraft.world.biome.Biome;
import net.minecraft.world.gen.GenerationStep;
import net.minecraft.world.gen.feature.DefaultFeatureConfig;
import net.minecraft.world.gen.feature.Feature;
import net.minecraft.world.gen.feature.PlacedFeature;
import net.minecraft.world.gen.structure.StructureType;

/**
 * 1.0 world loot: searchable trash cans and the "Bankrupt Card Shop" structure.
 * Call {@link #register()} from TcgShop.onInitialize (the static registrations happen when the class loads).
 *
 * <p>Data (generated by tools/gen_worldloot_assets.py): worldgen/configured_feature + placed_feature
 * trash_can_street / trash_can_wild, worldgen/structure + structure_set bankrupt_card_shop, biome tags
 * has_structure/bankrupt_card_shop and spawns_wild_trash_cans, the block's loot table and recipe.
 */
public final class WorldLoot {
    private WorldLoot() {}

    public static final TrashCanBlock TRASH_CAN = Registry.register(Registries.BLOCK, id("trash_can"),
            new TrashCanBlock(AbstractBlock.Settings.create().mapColor(MapColor.IRON_GRAY).strength(1.5f, 6f)
                    .sounds(BlockSoundGroup.LANTERN).nonOpaque()));
    public static final Item TRASH_CAN_ITEM = Registry.register(Registries.ITEM, id("trash_can"),
            new BlockItem(TRASH_CAN, new Item.Settings()));
    public static final BlockEntityType<TrashCanBlockEntity> TRASH_CAN_BE = Registry.register(Registries.BLOCK_ENTITY_TYPE, id("trash_can"),
            BlockEntityType.Builder.create(TrashCanBlockEntity::new, TRASH_CAN).build(null));

    public static final Feature<DefaultFeatureConfig> STREET_CANS = Registry.register(Registries.FEATURE, id("trash_can_street"), new TrashCanFeature(true));
    public static final Feature<DefaultFeatureConfig> WILD_CANS = Registry.register(Registries.FEATURE, id("trash_can_wild"), new TrashCanFeature(false));

    public static final StructureType<BankruptShopStructure> BANKRUPT_SHOP_TYPE = Registry.register(Registries.STRUCTURE_TYPE,
            id("bankrupt_card_shop"), (StructureType<BankruptShopStructure>) () -> BankruptShopStructure.CODEC);
    public static final StructurePieceType BANKRUPT_SHOP_PIECE = Registry.register(Registries.STRUCTURE_PIECE,
            id("bankrupt_card_shop"), (StructurePieceType.Simple) BankruptShopPiece::new);

    public static final RegistryKey<PlacedFeature> STREET_CANS_PLACED = RegistryKey.of(RegistryKeys.PLACED_FEATURE, id("trash_can_street"));
    public static final RegistryKey<PlacedFeature> WILD_CANS_PLACED = RegistryKey.of(RegistryKeys.PLACED_FEATURE, id("trash_can_wild"));
    /** Biomes with lonely trash cans (plains, meadows, savannas...). */
    public static final TagKey<Biome> WILD_CAN_BIOMES = TagKey.of(RegistryKeys.BIOME, id("spawns_wild_trash_cans"));

    private static Identifier id(String path) {
        return Identifier.of(TcgShop.MOD_ID, path);
    }

    public static void register() {
        WorldLootConfig.load();
        if (WorldLootConfig.INSTANCE.trashCansWorldgen) {
            // street cans look for dirt paths themselves: any overworld biome can hold a village street
            BiomeModifications.addFeature(BiomeSelectors.foundInOverworld(), GenerationStep.Feature.VEGETAL_DECORATION, STREET_CANS_PLACED);
            BiomeModifications.addFeature(BiomeSelectors.tag(WILD_CAN_BIOMES), GenerationStep.Feature.VEGETAL_DECORATION, WILD_CANS_PLACED);
        }
    }
}
